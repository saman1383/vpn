CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(10) NOT NULL DEFAULT 'user',
 active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 price_toman BIGINT UNSIGNED NOT NULL,
 volume_gb INT UNSIGNED NOT NULL,
 days INT UNSIGNED NOT NULL DEFAULT 30,
 devices INT UNSIGNED NOT NULL DEFAULT 2,
 inbound_id INT UNSIGNED NOT NULL DEFAULT 0,
 active TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS services (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 inbound_id INT UNSIGNED NOT NULL,
 client_email VARCHAR(100) NOT NULL UNIQUE,
 client_uuid CHAR(36) NOT NULL,
 sub_id CHAR(32) NOT NULL,
 total_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 expiry_ms BIGINT UNSIGNED NOT NULL DEFAULT 0,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (plan_id) REFERENCES plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 service_id BIGINT UNSIGNED NULL,
 renewal_service_id BIGINT UNSIGNED NULL,
 request_key VARCHAR(80) NOT NULL,
 months TINYINT NOT NULL,
 amount_rial BIGINT UNSIGNED NOT NULL,
 quota_bytes BIGINT UNSIGNED NOT NULL,
 duration_days INT UNSIGNED NOT NULL,
 devices INT UNSIGNED NOT NULL,
 inbound_id INT UNSIGNED NOT NULL,
 authority VARCHAR(100) NULL UNIQUE,
 ref_id VARCHAR(100) NULL UNIQUE,
 status VARCHAR(30) NOT NULL DEFAULT 'requesting',
 target_json MEDIUMTEXT NULL,
 verify_after BIGINT NOT NULL DEFAULT 0,
 last_error VARCHAR(80) NULL,
 paid_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY user_request (user_id,request_key),
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (plan_id) REFERENCES plans(id),
 FOREIGN KEY (service_id) REFERENCES services(id),
 FOREIGN KEY (renewal_service_id) REFERENCES services(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) PRIMARY KEY,
 hits INT UNSIGNED NOT NULL DEFAULT 0,
 reset_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tickets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'open',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ticket_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 body TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (ticket_id) REFERENCES tickets(id),
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
